import { existsSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawn } from 'node:child_process';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const repoRoot = path.resolve(__dirname, '..');
const apiRoot = path.join(repoRoot, 'apps', 'api');

const args = new Set(process.argv.slice(2));
const shouldMarkApplied = args.has('--mark-applied') || process.env.PRISMA_BASELINE_MARK_APPLIED === '1';
const baselineName = process.env.PRISMA_BASELINE_NAME || '20260331000000_baseline';
const baselineDir = path.join(apiRoot, 'prisma', 'migrations', baselineName);
const baselineSqlPath = path.join(baselineDir, 'migration.sql');
const lockPath = path.join(apiRoot, 'prisma', 'migrations', 'migration_lock.toml');

async function run() {
  await mkdir(path.dirname(lockPath), { recursive: true });
  if (!existsSync(lockPath)) {
    await writeFile(lockPath, [
      '# Please do not edit this file manually',
      '# It should be added in your version-control system (e.g., Git)',
      'provider = "sqlite"',
      '',
    ].join('\n'), 'utf8');
  }

  if (!existsSync(baselineSqlPath)) {
    await mkdir(baselineDir, { recursive: true });
    const diff = await execCapture(
      'pnpm',
      [
        '--filter',
        '@occ/api',
        'exec',
        'prisma',
        'migrate',
        'diff',
        '--from-empty',
        '--to-schema-datamodel',
        'prisma/schema.prisma',
        '--script',
      ],
      { cwd: repoRoot },
    );

    const normalized = diff.stdout.trim();
    if (!normalized) {
      throw new Error('生成基线迁移失败：migrate diff 返回空内容');
    }

    await writeFile(baselineSqlPath, `${normalized}\n`, 'utf8');
    process.stdout.write(`✅ 已生成基线迁移: ${path.relative(repoRoot, baselineSqlPath)}\n`);
  } else {
    process.stdout.write(`ℹ️ 基线迁移已存在: ${path.relative(repoRoot, baselineSqlPath)}\n`);
  }

  if (shouldMarkApplied) {
    await execStream('pnpm', ['--filter', '@occ/api', 'exec', 'prisma', 'migrate', 'resolve', '--applied', baselineName], {
      cwd: repoRoot,
    });
    process.stdout.write(`✅ 已标记基线为已应用: ${baselineName}\n`);
  } else {
    process.stdout.write('ℹ️ 未执行 migrate resolve（如需标记当前库已应用基线，请追加 --mark-applied）。\n');
  }
}

function execStream(command, args, options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      stdio: 'inherit',
      shell: process.platform === 'win32',
      ...options,
    });

    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) {
        resolve();
        return;
      }
      reject(new Error(`命令失败: ${command} ${args.join(' ')} (exit=${code})`));
    });
  });
}

function execCapture(command, args, options = {}) {
  return new Promise((resolve, reject) => {
    const child = spawn(command, args, {
      shell: process.platform === 'win32',
      ...options,
      stdio: ['ignore', 'pipe', 'pipe'],
    });

    let stdout = '';
    let stderr = '';

    child.stdout.on('data', (chunk) => {
      stdout += String(chunk);
    });
    child.stderr.on('data', (chunk) => {
      stderr += String(chunk);
    });

    child.on('error', reject);
    child.on('close', (code) => {
      if (code === 0) {
        resolve({ stdout, stderr });
        return;
      }
      reject(new Error(`命令失败: ${command} ${args.join(' ')}\n${stderr || stdout}`));
    });
  });
}

run().catch(async (error) => {
  let extra = '';
  try {
    if (existsSync(baselineSqlPath)) {
      const content = await readFile(baselineSqlPath, 'utf8');
      if (!content.trim()) {
        extra = '\n检测到生成的 migration.sql 为空，请检查 prisma schema。';
      }
    }
  } catch {
    // ignore
  }
  process.stderr.write(`❌ Prisma 基线处理失败: ${error instanceof Error ? error.message : String(error)}${extra}\n`);
  process.exitCode = 1;
});
